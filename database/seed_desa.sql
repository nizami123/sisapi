INSERT INTO desa (kecamatan_id,nama,is_active,created_at)
SELECT k.id,i.nama,1,NOW() FROM d_import i JOIN kecamatan k ON k.nama=i.kecamatan
WHERE NOT EXISTS (SELECT 1 FROM desa x WHERE x.kecamatan_id=k.id AND x.nama=i.nama);
-- Baris di d_import yang namanya tidak cocok dengan kecamatan manapun (harus 0):
SELECT COUNT(*) AS desa_tidak_cocok_kecamatan FROM d_import i LEFT JOIN kecamatan k ON k.nama=i.kecamatan WHERE k.id IS NULL;
